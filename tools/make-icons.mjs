// Makes src/components/icon/admin-glyphs.ts: the MingCute icons that the
// admin panel needs and the mobile app does not have. The app icons are in
// src/components/icon/glyphs.ts, a copy of realstay-prod
// components/icon/glyphs.ts, so both use the same icons.
//
// Run it again after a change: node tools/make-icons.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const ADMIN_ICONS = {
  "menu": "menu-line",
  "sidebar": "layout-left-line",
  "notifications-outline": "notification-line",
  "settings-outline": "settings-3-line",
  "desktop-outline": "computer-line",
  "sunny-outline": "sun-line",
  "moon-outline": "moon-line",
};

const require = createRequire(import.meta.url);
const iconSet = JSON.parse(
  readFileSync(require.resolve("@iconify-json/mingcute/icons.json"), "utf8"),
);

const lines = Object.entries(ADMIN_ICONS).map(([name, icon]) => {
  const match = iconSet.icons[icon]?.body.match(
    /^<path fill="currentColor" d="([^"]+)"\/>$/,
  );
  if (!match) throw new Error(`MingCute icon ${icon} is not one filled path`);
  return `  ${JSON.stringify(name)}: ${JSON.stringify({ d: match[1] })},`;
});

writeFileSync(
  "src/components/icon/admin-glyphs.ts",
  `// Generated by tools/make-icons.mjs from MingCute (Apache-2.0). Do not edit.\n\nexport const ADMIN_GLYPHS = {\n${lines.join("\n")}\n} as const;\n`,
);
